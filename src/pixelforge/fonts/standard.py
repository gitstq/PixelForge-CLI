    def get_char(self, char: str) -> list:
        """Get the ASCII pattern for a character."""
        upper_char = char.upper()
        if upper_char in self.CHARS:
            return self.CHARS[upper_char]
        # Return blank pattern for unknown characters
        return ["      " for _ in range(self.height)]
    
    def render(self, text: str) -> list:
        """
        Render text string to ASCII art.
        
        Args:
            text: Text string to render
            
        Returns:
            List of strings, each representing one line of the output
        """
        if not text:
            return []
        
        # Get patterns for each character
        char_patterns = [self.get_char(c) for c in text]
        
        # Combine patterns horizontally
        result = []
        for row in range(self.height):
            line = ""
            for pattern in char_patterns:
                if row < len(pattern):
                    line += pattern[row]
            result.append(line.rstrip())
        
        return result
